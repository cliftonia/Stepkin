    //   Row 8:  ...##########...     ...##########...
    //   Row 9:  ..##.####.###..     ...##########...
    //   Row10:  ..############.     ....########....
    //   Row11:  ..############.     .....######.....
    //   Row14:  ......####......     ................

    static func dotkinFrames(
        _ kind: AnimationKind
    ) -> [SpriteFrame] {
        let idle1 = SpriteFrame(rows: [
            0x0000, //  ................
            0x0000, //  ................
            0x0000, //  ................
            0x0000, //  ................
            0x0000, //  ................
            0x0000, //  ................
            0x03C0, //  ......####......
