import Foundation

// MARK: - Orbkin (Ultimate) - round body, big glove hand

extension SpriteCatalog {

    static func orbkinFrames(
        _ kind: AnimationKind
    ) -> [SpriteFrame] {
        let idle1 = SpriteFrame(rows: [
            0x0000, //  ................
            0x0000, //  ................
            0x03C0, //  ......####......  head
            0x07E0, //  .....######.....
            0x0FF0, //  ....########....
            0x0DB0, //  ....##.##.##....  eyes
            0x0FF0, //  ....########....
            0x0E70, //  ....###..###....
            0x1FF8, //  ...##########...
            0x1FF8, //  ...##########...
            0xFFF0, //  ############....  big glove arm
            0xFFF0, //  ############....
            0x1FF8, //  ...##########...
            0x0FF0, //  ....########....
            0x0480, //  .....#..#.......  legs
            0x0CC0  //  ....##..##......  feet
        ])

        let idle2 = SpriteFrame(rows: [
            0x0000, 0x0000,
            0x03C0, 0x07E0, 0x0FF0,
            0x0DB0, 0x0FF0, 0x0E70,
            0x1FF8, 0x1FF8,
            0x0FFF, //  ....############  glove other side
            0x0FFF,
            0x1FF8,
            0x0FF0,
            0x0480,
            0x0CC0
        ])

        // Smiley Bomb (Mega Bomb) — glove winds back for the tell
        let attack1 = SpriteFrame(rows: [
            0x0000, //  ................
            0x0000, //  ................
            0x03C0, //  ......####......  head
            0x07E0, //  .....######.....
            0x0FF0, //  ....########....
            0x0DB0, //  ....##.##.##....  eyes
            0x0FF0, //  ....########....
            0x0FF0, //  ....########....  body
            0x1FF8, //  ...##########...
            0x1FF8, //  ...##########...
            0x1FFC, //  ...###########..  glove wound back
            0x1FFC, //  ...###########..
            0x1FF8, //  ...##########...
            0x0FF0, //  ....########....
            0x0480, //  .....#..#.......
            0x0CC0  //  ....##..##......
        ])

        // Side profile based on the idle: round body, one eye, beak
        // at the front, tail tuft at the back.
        let sideWalk1 = SpriteFrame(rows: [
            0x0000, //  ................
            0x0000, //  ................
            0x03C0, //  ......####......  head
            0x07E0, //  .....######.....
            0x0FF0, //  ....########....
            0x15F8, //  ...#.#.######...  beak + one eye
            0x3DF8, //  ..####.######...  beak
            0x0FF0, //  ....########....
            0x1FF8, //  ...##########...  body
            0x1FFC, //  ...###########..  tail
            0x1FFE, //  ...############.  tail tuft
            0x1FF8, //  ...##########...
            0x1FF8, //  ...##########...
            0x0FF0, //  ....########....
            0x0480, //  .....#..#.......  legs
            0x0CC0  //  ....##..##......  feet
        ])

        // Same bird, alternate feet for the walk.
        let sideWalk2 = SpriteFrame(rows: [
            0x0000, //  ................
            0x0000, //  ................
            0x03C0, //  ......####......  head
            0x07E0, //  .....######.....
            0x0FF0, //  ....########....
            0x15F8, //  ...#.#.######...  beak + one eye
            0x3DF8, //  ..####.######...  beak
            0x0FF0, //  ....########....
            0x1FF8, //  ...##########...  body
            0x1FFC, //  ...###########..  tail
            0x1FFE, //  ...############.  tail tuft
            0x1FF8, //  ...##########...
            0x1FF8, //  ...##########...
            0x0FF0, //  ....########....
            0x0240, //  ......#..#......  legs
            0x0660  //  .....##..##.....  feet
        ])

        switch kind {
        case .idle, .walk:
            return [idle1, idle2]
        case .sideWalk:
            return [sideWalk1, sideWalk2]
        case .happy, .eat, .sleep:
            return defaultAnimationFromIdle(idle1, idle2, kind)
        case .attack:
            return strike(idle: idle1, attack1)
        case .refuse:
            return defaultAnimationFromIdle(idle1, idle2, kind)
        }
    }
}
